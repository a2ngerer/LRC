"""Budget sizing table of the suite defaults (issue #59).

For every cell x wiring at the two suite budgets (Lotka-Volterra builder at 4k,
the rollout tasks; Person Activity at 30k) runs the runners' --param-budget
pick, ``size_for_budget(build, budget, budget_sizes(wiring))``, with the
runners' default cell kwargs and the final-suite backbone (--backbone-layers 1,
CfC family), seed 0. Writes a markdown table (size, effective parameters,
signed deviation, budget_above_tolerance).

Usage:
    uv run python experiments/budget_sizing_table.py [--out docs/budget-sizing.md]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiments.run_lotka_volterra_benchmark import BUDGET_TOLERANCE  # noqa: E402
from experiments.run_person_activity_benchmark import CELL_KWARGS  # noqa: E402
from src.tasks.lotka_volterra.model import build_lotka_volterra_model  # noqa: E402
from src.tasks.person_activity import load_person_activity  # noqa: E402
from src.tasks.person_activity.model import (  # noqa: E402
    backbone_override, budget_sizes, build_person_activity_model,
    dt_feature_applies, ode_unfolds_override)
from src.wirings import size_for_budget  # noqa: E402

CELLS = ("cfc_lrc", "cfc", "cfc_static", "lrc", "gru", "ctrnn")
WIRINGS = ("dense", "dense3", "ncp", "cncp")
BACKBONE = 1
ODE_UNFOLDS = 6


def cell_kwargs(cell):
    """The runners' default cell kwargs at --backbone-layers 1."""
    kw = dict(CELL_KWARGS.get(cell, {}))
    kw.update(backbone_override(cell, BACKBONE))
    kw.update(ode_unfolds_override(cell, ODE_UNFOLDS))
    return kw


def builders():
    pa = load_person_activity()
    return {
        "rollout (LV builder)": (4000, lambda w, c: lambda s:
            build_lotka_volterra_model(w, c, size=s, seed=0, **cell_kwargs(c))),
        "person activity": (30000, lambda w, c: lambda s:
            build_person_activity_model(
                w, c, size=s, seed=0, num_classes=pa.num_classes,
                feature_size=pa.feature_size, seq_len=pa.seq_len,
                dt_feature=dt_feature_applies(c), **cell_kwargs(c))),
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/budget-sizing.md")
    args = ap.parse_args(argv)
    rows = []
    for task, (budget, make) in builders().items():
        for cell in CELLS:
            for wiring in WIRINGS:
                size, n = size_for_budget(make(wiring, cell), budget,
                                          budget_sizes(wiring))
                dev = (n - budget) / budget
                rows.append(f"| {task} | {budget} | {cell} | {wiring} | {size:g} "
                            f"| {n} | {dev:+.1%} "
                            f"| {abs(dev) > BUDGET_TOLERANCE} |")
                print(rows[-1], flush=True)
    text = "\n".join([
        "# Budget sizing of the suite defaults",
        "",
        "Generated by `experiments/budget_sizing_table.py` (issue #59): the",
        "runners' `--param-budget` pick per arm, seed 0, `--backbone-layers 1`",
        "(CfC family), default cell kwargs. cncp scans the fractional lamina",
        "knob (`scaled_lamina_units`), every other wiring the integer sizes up",
        f"to 512. Tolerance {BUDGET_TOLERANCE:.0%} on the effective count.",
        "",
        "| Task | Budget | Cell | Wiring | Size | params_effective | Deviation "
        "| budget_above_tolerance |",
        "|------|--------|------|--------|------|------------------|-----------"
        "|------------------------|",
        *rows, ""])
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Written: {args.out}")


if __name__ == "__main__":
    main()
